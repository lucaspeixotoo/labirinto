void exibirLabirinto(void) {
	int maxCol = COL;
	int maxRow = ROW;
	
	printf("Exibindo Labirinto\n");
	
	for (int i = 0; i < maxRow; i++) {
		for (int j = 0; j < maxCol; j++) {
			printf("%c", labirinto[i][j]);
		}
		printf("\n");
	}	
}

Posicao localizar (char alvo) {
	Posicao p;
	
	for (int i = 0; i < COL; i++) {
		for (int j = 0; j < ROW; j++) {
			if (labirinto [i][j] == alvo) {
				p.linha = i;
				p.coluna = j;
				return p;
			}
		}
	}
	p.linha = -1;
	p.coluna = -1;
	return p;
}